import { describe, it, expect, vi } from 'vitest';
import {
  PDF_COLORS,
  PDF_LAYOUT,
  drawDocumentHeader,
  drawDocumentFooter,
} from './pdfBranding';

describe('pdfBranding', () => {
  it('defines 7TIME corporate brand palette with matching RGB tuples', () => {
    expect(PDF_COLORS.primaryNavy).toBe('#172B4D');
    expect(PDF_COLORS.primaryNavyRgb).toEqual([23, 43, 77]);

    expect(PDF_COLORS.accentBlue).toBe('#2563EB');
    expect(PDF_COLORS.accentBlueRgb).toEqual([37, 99, 235]);

    expect(PDF_COLORS.borderGray).toBe('#E2E8F0');
    expect(PDF_COLORS.surfaceLight).toBe('#F8FAFC');
  });

  it('defines A4 layout constants and computes content width correctly', () => {
    expect(PDF_LAYOUT.pageWidth).toBe(210);
    expect(PDF_LAYOUT.pageHeight).toBe(297);
    expect(PDF_LAYOUT.marginLeft).toBe(15);
    expect(PDF_LAYOUT.marginRight).toBe(15);
    expect(PDF_LAYOUT.contentWidth).toBe(180);
  });

  describe('drawDocumentHeader', () => {
    const createMockDoc = () => ({
      setFillColor: vi.fn(),
      setTextColor: vi.fn(),
      setDrawColor: vi.fn(),
      setLineWidth: vi.fn(),
      setFont: vi.fn(),
      setFontSize: vi.fn(),
      roundedRect: vi.fn(),
      text: vi.fn(),
      line: vi.fn(),
      getTextWidth: vi.fn().mockReturnValue(18),
    });

    it('draws 7TIME logo, title, category badge, and reference details', () => {
      const mockDoc = createMockDoc();

      const nextY = drawDocumentHeader(mockDoc, {
        title: 'Personal Ledger Statement',
        subtitle: 'John Doe',
        referenceNumber: 'REC-2026-001',
        workspaceName: '7TIME Primary Enterprise',
        date: '2026-11-10',
        category: 'STATEMENT',
      });

      // Renders 7TIME brand badge
      expect(mockDoc.roundedRect).toHaveBeenCalled();
      expect(mockDoc.text).toHaveBeenCalledWith('7TIME', expect.any(Number), expect.any(Number));
      expect(mockDoc.text).toHaveBeenCalledWith(
        'BUSINESS MANAGEMENT',
        expect.any(Number),
        expect.any(Number)
      );

      // Renders title and category
      expect(mockDoc.text).toHaveBeenCalledWith(
        'Personal Ledger Statement',
        expect.any(Number),
        expect.any(Number)
      );
      expect(mockDoc.text).toHaveBeenCalledWith('STATEMENT', expect.any(Number), expect.any(Number));

      // Returns subsequent content coordinate
      expect(nextY).toBeGreaterThan(30);
    });
  });

  describe('drawDocumentFooter', () => {
    it('draws divider and page numbers across all pages', () => {
      const mockDoc = {
        getNumberOfPages: vi.fn().mockReturnValue(3),
        setPage: vi.fn(),
        setDrawColor: vi.fn(),
        setLineWidth: vi.fn(),
        setTextColor: vi.fn(),
        setFont: vi.fn(),
        setFontSize: vi.fn(),
        line: vi.fn(),
        text: vi.fn(),
      };

      drawDocumentFooter(mockDoc);

      expect(mockDoc.getNumberOfPages).toHaveBeenCalled();
      expect(mockDoc.setPage).toHaveBeenCalledWith(1);
      expect(mockDoc.setPage).toHaveBeenCalledWith(2);
      expect(mockDoc.setPage).toHaveBeenCalledWith(3);

      expect(mockDoc.text).toHaveBeenCalledWith(
        'Generated by 7TIME Business Management • Electronic Record',
        expect.any(Number),
        expect.any(Number)
      );
      expect(mockDoc.text).toHaveBeenCalledWith('Page 1 of 3', expect.any(Number), expect.any(Number), {
        align: 'right',
      });
      expect(mockDoc.text).toHaveBeenCalledWith('Page 3 of 3', expect.any(Number), expect.any(Number), {
        align: 'right',
      });
    });
  });
});

